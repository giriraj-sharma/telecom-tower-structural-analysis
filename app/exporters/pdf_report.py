import io
from datetime import datetime
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether, HRFlowable
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch

from app.models.schemas import AnalysisOutput, TowerInput

def generate_pdf_report(analysis: AnalysisOutput, tower_input: TowerInput) -> bytes:
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )
    
    styles = getSampleStyleSheet()
    
    # Custom styles
    primary_color = colors.HexColor("#1e293b") # Dark slate
    accent_color = colors.HexColor("#0284c7")  # Deep sky blue
    safe_color = colors.HexColor("#16a34a")    # Emerald green
    warning_color = colors.HexColor("#d97706") # Amber
    fail_color = colors.HexColor("#dc2626")    # Red
    
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=20,
        leading=24,
        textColor=primary_color,
        spaceAfter=4
    )
    
    subtitle_style = ParagraphStyle(
        'DocSubTitle',
        parent=styles['Normal'],
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#64748b")
    )
    
    section_heading = ParagraphStyle(
        'SectionHeading',
        parent=styles['Heading2'],
        fontSize=12,
        leading=16,
        textColor=primary_color,
        spaceBefore=12,
        spaceAfter=6,
        keepWithNext=True
    )
    
    body_style = ParagraphStyle(
        'Body',
        parent=styles['Normal'],
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#334155")
    )
    
    disclaimer_style = ParagraphStyle(
        'Disclaimer',
        parent=styles['Normal'],
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#b45309")
    )
    
    elements = []
    
    # Header Title Block
    elements.append(Paragraph("TELECOM TOWER STRUCTURAL ANALYSIS REPORT", title_style))
    elements.append(Paragraph(
        f"Preliminary Structural Design & Load Optimization Calculation Book &bull; Generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}",
        subtitle_style
    ))
    elements.append(Spacer(1, 8))
    
    # Disclaimer Box
    disclaimer_text = (
        "<b>ENGINEERING NOTICE & EDUCATIONAL DISCLAIMER:</b> This report is generated by a preliminary "
        "structural analysis and design optimization application for academic, educational, and preliminary planning "
        "purposes. It is NOT a certified structural design package and must not be used for construction without "
        "independent verification and stamping by a licensed Professional Structural Engineer (PE/SE)."
    )
    disclaimer_table = Table([[Paragraph(disclaimer_text, disclaimer_style)]], colWidths=[540])
    disclaimer_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#fef3c7")),
        ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#f59e0b")),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
    ]))
    elements.append(disclaimer_table)
    elements.append(Spacer(1, 10))
    
    # Status Banner
    status_color = safe_color if analysis.overall_status == "SAFE" else (warning_color if analysis.overall_status == "WARNING" else fail_color)
    status_summary = [
        [
            Paragraph("<b>Overall Status</b>", body_style),
            Paragraph(f"<b><font color='{status_color.hexval()}'>{analysis.overall_status}</font></b>", title_style),
            Paragraph("<b>Max Utilization</b>", body_style),
            Paragraph(f"<b>{round(analysis.max_utilization * 100, 1)}%</b>", title_style),
            Paragraph("<b>Safety Factor</b>", body_style),
            Paragraph(f"<b>{analysis.safety_factor}</b>", title_style)
        ]
    ]
    status_table = Table(status_summary, colWidths=[80, 100, 85, 95, 80, 100])
    status_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
        ('BOX', (0, 0), (-1, -1), 1, colors.HexColor("#cbd5e1")),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(status_table)
    elements.append(Spacer(1, 10))
    
    # 1. Key Performance Indicators & Executive Summary
    elements.append(Paragraph("1. Executive Summary & Key Results", section_heading))
    kpi_data = [
        [
            Paragraph("<b>Tower Height:</b>", body_style), Paragraph(f"{analysis.height_m:.1f} m", body_style),
            Paragraph("<b>Governing Load Case:</b>", body_style), Paragraph(f"{analysis.governing_load_combination}", body_style)
        ],
        [
            Paragraph("<b>Base / Top Width:</b>", body_style), Paragraph(f"{analysis.base_width_m:.1f} m / {analysis.top_width_m:.1f} m", body_style),
            Paragraph("<b>Critical Member:</b>", body_style), Paragraph(f"{analysis.critical_member.member_id} ({analysis.critical_member.member_type})", body_style)
        ],
        [
            Paragraph("<b>Base Shear:</b>", body_style), Paragraph(f"{analysis.base_shear_kn:.2f} kN", body_style),
            Paragraph("<b>Max Lateral Deflection:</b>", body_style), Paragraph(f"{analysis.max_deflection_mm:.1f} mm ({analysis.deflection_ratio})", body_style)
        ],
        [
            Paragraph("<b>Overturning Moment:</b>", body_style), Paragraph(f"{analysis.overturning_moment_knm:.2f} kN&bull;m", body_style),
            Paragraph("<b>Antenna Tilt at Top:</b>", body_style), Paragraph(f"{analysis.top_tilt_angle_deg:.3f}&deg; (&le; 1.0&deg; limit)", body_style)
        ],
        [
            Paragraph("<b>Max Leg Uplift (Tension):</b>", body_style), Paragraph(f"{analysis.max_base_uplift_kn:.2f} kN", body_style),
            Paragraph("<b>Total Steel Mass:</b>", body_style), Paragraph(f"{analysis.total_steel_weight_tonnes:.2f} tonnes", body_style)
        ],
        [
            Paragraph("<b>Max Leg Compression:</b>", body_style), Paragraph(f"{analysis.max_base_compression_kn:.2f} kN", body_style),
            Paragraph("<b>Estimated Cost:</b>", body_style), Paragraph(f"${analysis.estimated_cost_usd:,.2f} USD", body_style)
        ]
    ]
    kpi_table = Table(kpi_data, colWidths=[135, 135, 135, 135])
    kpi_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#ffffff")),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(kpi_table)
    elements.append(Spacer(1, 10))
    
    # 2. Design Input Parameters & Environmental Loading
    elements.append(Paragraph("2. Design Input & Loading Parameters", section_heading))
    input_data = [
        [Paragraph("<b>Parameter</b>", body_style), Paragraph("<b>Configured Value</b>", body_style), Paragraph("<b>Standard / Equation Reference</b>", body_style)],
        [Paragraph("Tower Geometry", body_style), Paragraph(f"{tower_input.tower_type.upper()} Lattice ({tower_input.bracing_type})", body_style), Paragraph("Symmetrical space truss topology", body_style)],
        [Paragraph("Leg Member Section", body_style), Paragraph(f"{tower_input.leg_section_type} {tower_input.leg_dimension_mm} x {tower_input.leg_thickness_mm} mm", body_style), Paragraph("AISC 360 / EN 1993-1-1 Class 1/2", body_style)],
        [Paragraph("Bracing Member Section", body_style), Paragraph(f"{tower_input.brace_section_type} {tower_input.brace_dimension_mm} x {tower_input.brace_thickness_mm} mm", body_style), Paragraph("Equal angle diagonal web members", body_style)],
        [Paragraph("Structural Steel Grade", body_style), Paragraph(f"Fy = {tower_input.steel_yield_strength_mpa:.0f} MPa, E = {tower_input.steel_elastic_modulus_gpa:.0f} GPa", body_style), Paragraph("Structural Carbon Steel (S355/A36)", body_style)],
        [Paragraph("Basic Wind Speed (V)", body_style), Paragraph(f"{tower_input.wind_speed_kmh:.1f} km/h ({tower_input.wind_speed_kmh/3.6:.1f} m/s)", body_style), Paragraph("3-second gust design wind velocity", body_style)],
        [Paragraph("Terrain Category", body_style), Paragraph(f"{tower_input.terrain_category}", body_style), Paragraph("Exposure profile velocity coeff Kz", body_style)],
        [Paragraph("Gust Factor (Gh)", body_style), Paragraph(f"{tower_input.gust_factor:.2f}", body_style), Paragraph("Dynamic lattice gust response factor", body_style)],
        [Paragraph("Appurtenance Antenna Count", body_style), Paragraph(f"{len(tower_input.equipment_items)} item groups", body_style), Paragraph("TIA-222 EPA projected drag & dead load", body_style)]
    ]
    input_table = Table(input_data, colWidths=[160, 180, 200])
    input_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(input_table)
    elements.append(Spacer(1, 10))

    # 3. Load Combinations Evaluation
    elements.append(Paragraph("3. Load Combinations Summary & Governing Case", section_heading))
    combo_rows = [
        [
            Paragraph("<b>Load Case</b>", body_style),
            Paragraph("<b>Description</b>", body_style),
            Paragraph("<b>Base Shear</b>", body_style),
            Paragraph("<b>Moment</b>", body_style),
            Paragraph("<b>Defl. (mm)</b>", body_style),
            Paragraph("<b>Max Util.</b>", body_style),
            Paragraph("<b>Status</b>", body_style)
        ]
    ]
    for c in analysis.load_combinations:
        st_color = safe_color if c.status == "SAFE" else (warning_color if c.status == "WARNING" else fail_color)
        is_gov = c.name == analysis.governing_load_combination
        name_txt = f"<b>{c.name} *</b>" if is_gov else c.name
        combo_rows.append([
            Paragraph(name_txt, body_style),
            Paragraph(c.description, body_style),
            Paragraph(f"{c.base_shear_kn:.1f} kN", body_style),
            Paragraph(f"{c.overturning_moment_knm:.1f} kNm", body_style),
            Paragraph(f"{c.max_deflection_mm:.1f}", body_style),
            Paragraph(f"<b>{round(c.max_overall_utilization * 100, 1)}%</b>", body_style),
            Paragraph(f"<font color='{st_color.hexval()}'><b>{c.status}</b></font>", body_style)
        ])
    combo_table = Table(combo_rows, colWidths=[90, 150, 65, 75, 55, 55, 50])
    combo_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ('ALIGN', (2, 0), (-1, -1), 'CENTER'),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
    ]))
    elements.append(combo_table)
    elements.append(Spacer(1, 10))

    # 4. Critical Member Capacity & Stress Verification
    elements.append(Paragraph("4. Governing Critical Member Verification", section_heading))
    crit = analysis.critical_member
    crit_rows = [
        [Paragraph("<b>Check Attribute</b>", body_style), Paragraph("<b>Calculation / Specification</b>", body_style), Paragraph("<b>Status Check</b>", body_style)],
        [Paragraph("Member Identifier", body_style), Paragraph(crit.member_id, body_style), Paragraph("Selected worst-case element", body_style)],
        [Paragraph("Member Type / Location", body_style), Paragraph(f"{crit.member_type} at elevation {crit.elevation_m:.1f} m", body_style), Paragraph("Panel critical section", body_style)],
        [Paragraph("Section Profile", body_style), Paragraph(crit.section_description, body_style), Paragraph("Standard structural shape", body_style)],
        [Paragraph("Axial Demand Force (Pu)", body_style), Paragraph(f"{crit.axial_force_kn:.2f} kN", body_style), Paragraph("Governing combo internal force", body_style)],
        [Paragraph("Member Design Capacity (Pn)", body_style), Paragraph(f"{crit.capacity_kn:.2f} kN", body_style), Paragraph("Euler/AISC column buckling curve", body_style)],
        [Paragraph("Slenderness Ratio (KL/r)", body_style), Paragraph(f"&lambda; = {crit.slenderness_ratio:.1f} (&le; 150 leg / 200 brace)", body_style), Paragraph("Satisfies slenderness limit", body_style)],
        [Paragraph("Critical Buckling Stress (Fcr)", body_style), Paragraph(f"{crit.critical_stress_mpa:.1f} MPa", body_style), Paragraph("Inelastic/elastic buckling stress", body_style)],
        [Paragraph("Stress Utilization Ratio (U)", body_style), Paragraph(f"<b>{round(crit.utilization_ratio * 100, 1)}%</b>", body_style), Paragraph(f"<b><font color='{status_color.hexval()}'>{crit.status}</font></b>", body_style)]
    ]
    crit_table = Table(crit_rows, colWidths=[170, 190, 180])
    crit_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(crit_table)
    elements.append(Spacer(1, 10))

    # 5. Cost & Material Takeoff Breakdown
    elements.append(Paragraph("5. Material Takeoff & Cost Estimation Summary", section_heading))
    cost = analysis.cost_breakdown
    cost_rows = [
        [Paragraph("<b>Component</b>", body_style), Paragraph("<b>Basis / Weight</b>", body_style), Paragraph("<b>Estimated Cost (USD)</b>", body_style)],
        [Paragraph("Structural Steel Material", body_style), Paragraph(f"{cost.steel_mass_kg:,.1f} kg @ $2.20/kg", body_style), Paragraph(f"${cost.steel_cost_usd:,.2f}", body_style)],
        [Paragraph("Shop Fabrication & Galvanizing", body_style), Paragraph(f"{cost.steel_mass_kg:,.1f} kg @ $1.10/kg", body_style), Paragraph(f"${cost.fabrication_galvanizing_usd:,.2f}", body_style)],
        [Paragraph("Hardware, Step Bolts & Ladders", body_style), Paragraph("Access ladder, safety climb & fasteners", body_style), Paragraph(f"${cost.hardware_and_accessories_usd:,.2f}", body_style)],
        [Paragraph("Substructure & Foundation Estimate", body_style), Paragraph("Reinforced concrete piers & foundation pad", body_style), Paragraph(f"${cost.foundation_estimate_usd:,.2f}", body_style)],
        [Paragraph("<b>Total Estimated Tower Project Cost</b>", body_style), Paragraph("<b>Excluding land acquisition & telecom electronics</b>", body_style), Paragraph(f"<b>${cost.total_estimated_cost_usd:,.2f}</b>", body_style)]
    ]
    cost_table = Table(cost_rows, colWidths=[200, 180, 160])
    cost_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
        ('BACKGROUND', (0, -1), (-1, -1), colors.HexColor("#f8fafc")),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(cost_table)
    
    # Build document
    doc.build(elements)
    buffer.seek(0)
    return buffer.getvalue()
